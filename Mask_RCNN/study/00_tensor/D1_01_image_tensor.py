import torch


# ============================================================
# 1. 创建一个模拟的 RGB 图片 Tensor
# ============================================================

# shape:
# B = 1      一次放进网络 1 张图片
# C = 3      RGB 三个通道
# H = 640    图片高度
# W = 640    图片宽度
x = torch.randn(1, 3, 640, 640)

print("完整 Tensor 的 shape：")
print(x.shape)


# ============================================================
# 2. 分别取出 R、G、B 三个通道
# ============================================================

r_channel = x[:, 0]
g_channel = x[:, 1]
b_channel = x[:, 2]

print("\nR 通道 shape：")
print(r_channel.shape)

print("\nG 通道 shape：")
print(g_channel.shape)

print("\nB 通道 shape：")
print(b_channel.shape)


# ============================================================
# 3. 保留通道这一维
# ============================================================

r_channel_keep_dim = x[:, 0:1]

print("\nR 通道，但保留 channel 维度：")
print(r_channel_keep_dim.shape)


# ============================================================
# 4. 查看一小块数据
# ============================================================

print("\n第 1 张图片，第 1 个通道左上角 3×3 数据：")
print(x[0, 0, 0:3, 0:3])


# ============================================================
# 5. 查看一个位置上的三个通道值
# ============================================================

print("\n位置 H=100, W=200 的三个通道值：")
print(x[0, :, 100, 200])

# ============================================================
# 6. 验证猜测
# ============================================================

print("\n验证猜测：")

print(x.shape)

print(x[0].shape)

print(x[:, 0].shape)

print(x[:, 0:1].shape)

print(x[0, :, 100, 200].shape)

# ============================================================
# 7. 模拟经过一个卷积层
# ============================================================

conv = torch.nn.Conv2d(
    in_channels=3,
    out_channels=64,
    kernel_size=3,
    stride=1,
    padding=1,
)

y = conv(x)

print("\n经过 Conv2d 后：")
print("输入 shape :", x.shape)
print("输出 shape :", y.shape)

# ============================================================
# 8. x/y 的空间位置对应关系比较
# ============================================================

print("\n===== 卷积前后的 Tensor =====")

print("x.shape =", x.shape)
print("y.shape =", y.shape)

print("\nx 中一个空间位置的特征：")
print(x[0, :, 100, 200].shape)

print("\ny 中同一个空间位置的特征：")
print(y[0, :, 100, 200].shape)

print("\n一共有几个维度:",x.ndim())
print("\nTensor 一共有几个数:",x.numel())
